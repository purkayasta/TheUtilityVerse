using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace UtilityVerse.Copy.Generators;

internal static class DeepCopyGenerator
{
	internal static string? Generate(INamedTypeSymbol typeSymbol)
	{
		if (typeSymbol.IsAbstract) return null;
		if (!Helper.IsPartial(typeSymbol)) return null;

		var depth = Helper.ExtractDepth(typeSymbol, "DeepCopy");

		var isGlobalNamespace = typeSymbol.ContainingNamespace.IsGlobalNamespace;
		var namespaceName = isGlobalNamespace ? null : typeSymbol.ContainingNamespace.ToDisplayString();
		var typeName = typeSymbol.Name;

		var typeKind = typeSymbol switch
		{
			{ TypeKind: TypeKind.Class, IsRecord: true } => "record",
			{ TypeKind: TypeKind.Struct, IsRecord: true } => "record struct",
			{ TypeKind: TypeKind.Class } => "class",
			{ TypeKind: TypeKind.Struct } => "struct",
			_ => null
		};

		if (typeKind == null)
			return null;

		// Detect constructor strategy before allocating the StringBuilder
		var hasParameterlessCtor = typeSymbol.InstanceConstructors.Any(c => c.Parameters.Length == 0);
		IMethodSymbol? ctor = null;
		if (!hasParameterlessCtor)
		{
			ctor = typeSymbol.InstanceConstructors
				.OrderByDescending(c => c.Parameters.Length)
				.FirstOrDefault();

			if (ctor == null)
				return null;
		}

		var sb = new StringBuilder();

		sb.AppendLine("""

                      // <auto-generated>
                      //     This code was generated by Copy.
                      //     Author: Pritom Purkayasta
                      //     DO NOT modify this file manually. Changes may be overwritten.
                      //     This file contains auto-generated DeepCopy() implementations.
                      // </auto-generated>

                      using System;
                      using System.Linq;
                      using System.Collections.Generic;
                      using System.Collections.ObjectModel;
                      using System.Collections.Immutable;
                      using System.Collections.Concurrent;
                      using System.Collections.Frozen;

                      """);

		if (!string.IsNullOrEmpty(namespaceName))
		{
			sb.AppendLine($"namespace {namespaceName}");
			sb.AppendLine("{");
		}

		sb.AppendLine($"    public partial {typeKind} {typeName}");
		sb.AppendLine("    {");
		sb.AppendLine("        [System.CodeDom.Compiler.GeneratedCode(\"DeepCopyGenerator\", \"1.0\")]");
		sb.AppendLine($"        public {typeName} DeepCopy()");
		sb.AppendLine("        {");
		sb.AppendLine($"            var objectMap = new Dictionary<object, object>();");
		sb.AppendLine($"            return DeepCopyInternal(0, {depth}, objectMap);");
		sb.AppendLine("        }");
		sb.AppendLine();
		sb.AppendLine("        [System.CodeDom.Compiler.GeneratedCode(\"DeepCopyGenerator\", \"1.0\")]");
		sb.AppendLine($"        internal {typeName} DeepCopyInternal(int currentDepth, int maxDepth, Dictionary<object, object> objectMap)");
		sb.AppendLine("        {");

		if (!hasParameterlessCtor)
		{
			// Build a name-keyed property lookup to avoid O(n×m) repeated enumeration
			var propertyMap = Helper.GetAllProperties(typeSymbol)
				.ToDictionary(p => p.Name, System.StringComparer.OrdinalIgnoreCase);

			// For non-parameterless ctors, check identity map first (only for class types, not struct)
			if (typeSymbol.TypeKind == TypeKind.Class || typeSymbol.IsRecord)
			{
				sb.AppendLine("            // Check if already copied (handles circular references)");
				sb.AppendLine("            if (objectMap.TryGetValue(this, out var existing))");
				sb.AppendLine($"                return ({typeName})existing;");
				sb.AppendLine();
			}

			var args = ctor!.Parameters.Select(p =>
			{
				if (!propertyMap.TryGetValue(p.Name, out var prop))
					return $"default({p.Type.ToDisplayString()})";

				return Helper.GenerateDeepCopyAssignment(prop.Type, prop.Name, withObjectMap: true);
			});

			sb.AppendLine($"            var copy = new {typeName}({string.Join(", ", args)});");

			// Register the copy before recursing (prevents infinite loops in circular refs)
			if (typeSymbol.TypeKind == TypeKind.Class || typeSymbol.IsRecord)
			{
				sb.AppendLine("            objectMap[this] = copy;");
			}

			sb.AppendLine("            return copy;");
		}
		else
		{
			// For parameterless ctors, check identity map first (only for class types)
			if (typeSymbol.TypeKind == TypeKind.Class || typeSymbol.IsRecord)
			{
				sb.AppendLine("            // Check if already copied (handles circular references)");
				sb.AppendLine("            if (objectMap.TryGetValue(this, out var existing))");
				sb.AppendLine($"                return ({typeName})existing;");
				sb.AppendLine();

				// Create empty object first, register it, then set properties
				sb.AppendLine($"            var copy = new {typeName}();");
				sb.AppendLine("            objectMap[this] = copy;");
				sb.AppendLine();

				// Now set properties (after registration to handle circular refs)
				foreach (var member in Helper.GetAllProperties(typeSymbol))
				{
					if (member.IsReadOnly || member.SetMethod is null)
						continue;

					var assignment = Helper.GenerateDeepCopyAssignment(member.Type, member.Name, withObjectMap: true);
					sb.AppendLine($"            copy.{member.Name} = {assignment};");
				}

				sb.AppendLine("            return copy;");
			}
			else
			{
				// For structs, just use object initializer (no circular ref concern)
				sb.AppendLine($@"            return new {typeName}
            {{");

				foreach (var member in Helper.GetAllProperties(typeSymbol))
				{
					if (member.IsReadOnly || member.SetMethod is null)
						continue;

					var assignment = Helper.GenerateDeepCopyAssignment(member.Type, member.Name, withObjectMap: false);
					sb.AppendLine($"                {member.Name} = {assignment},");
				}

				sb.AppendLine(@"            };");
			}
		}

		sb.AppendLine("        }");
		sb.AppendLine("    }");

		if (!string.IsNullOrEmpty(namespaceName))
		{
			sb.AppendLine("}");
		}

		return sb.ToString();
	}
}
